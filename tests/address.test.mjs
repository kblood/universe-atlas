test("floorDivBig matches Euclidean floor division for BigInt, including negatives", () => {
  assert.equal(floorDivBig(7n, 2n), 3n);
  assert.equal(floorDivBig(-7n, 2n), -4n);
  assert.equal(floorDivBig(-1n, 8n), -1n);
  assert.equal(floorDivBig(0n, 8n), 0n);
  assert.equal(floorDivBig(8n, 8n), 1n);
  assert.equal(floorDivBig(-8n, 8n), -1n);
});

// ---------------------------------------------------------------------------
// Compatibility requirement 2: every existing address string form still
// resolves, with or without the U/K/H prefix, to clusterCell=groupCell=(0,0,0).
// ---------------------------------------------------------------------------
test("legacy address strings (no U/K/H prefix) parse to the zero cluster/group cell", () => {
  for (const s of ["G001/C2128,0,1/0", "G001/C-12,-4,7/3/star/0", "G032"]) {
    const a = parseAddress(s);
    assert.ok(a, `expected ${s} to parse`);
    assert.deepEqual(a.clusterCell, [0n, 0n, 0n]);
    assert.deepEqual(a.groupCell, [0n, 0n, 0n]);
  }
});

test("real system-address strings generated by sector() round-trip through parse/resolve", () => {
  const g = galaxies(SEED)[0];
  const refs = sector(g, [266, 0, 0]).refs.slice(0, 25);
  for (const ref of refs) {
    const parsed = parseAddress(ref.id);
    assert.ok(parsed, ref.id);
    assert.equal(parsed.galaxyOrdinal, 0);
    assert.deepEqual(parsed.genCell, ref.cell.map(BigInt));
    assert.equal(parsed.systemOrdinal, ref.ordinal);
    assert.deepEqual(parsed.sectorCell, [266n, 0n, 0n]);
    // format(parse(s)) === s for every legacy id catalog.ts actually produces.
    assert.equal(formatAddress(parsed), ref.id);
    // and it still resolves to the exact same object via the unchanged refByAddress.
    assert.deepEqual(refByAddress(g, formatAddress(parsed)), ref);
  }
});

test("round-trip format(parse(s)) === s, with and without the U/K/H prefix, at every address level", () => {
  const cases = [
    "G005",
    "G001/C2128,0,1/0",
    "G001/C-12,-4,7/3/star/0",
    "G041/C0,0,0/0/planet/3/moon/1",
    "U/K(12,-4,7)/H(3,1,18)/G007",
    "U/K(12,-4,7)/H(3,1,18)/G007/C184,-92,3/41",
    "U/K(12,-4,7)/H(3,1,18)/G007/C184,-92,3/41/star/0",
    "U/K(1000000000,-1000000000,3)/H(7,18,0)/G012/C0,0,0/0/planet/0",
  ];
  for (const s of cases) {
    const parsed = parseAddress(s);
    assert.ok(parsed, s);
    assert.equal(formatAddress(parsed), s, s);
  }
});

test("parseAddress rejects garbage", () => {
  for (const s of ["", "not-an-address", "G/C1,2,3/0", "G001/C1,2/0", "G001/Cx,y,z/0"]) {
    assert.equal(parseAddress(s), null, s);
  }
});

// ---------------------------------------------------------------------------
// Spatial-correctness fix (Issue 1): groupCell is a LOCAL offset within
// clusterCell (scheme a), not an independent hash key - a universe position
// must have exactly one valid address.
// ---------------------------------------------------------------------------
test("parseAddress rejects an out-of-range groupCell (non-canonical address)", () => {
  for (const s of [
    "U/K(0,0,0)/H(20,0,0)/G001",
    "U/K(0,0,0)/H(-1,0,0)/G001",
    "U/K(0,0,0)/H(0,20,0)/G001",
    "U/K(0,0,0)/H(0,0,-1)/G001",
    "U/K(3,-1,2)/H(7,0,-4)/G001", // the pre-fix HIERARCHY_SAMPLES entry, now rejected
    `U/K(0,0,0)/H(${CELLS_PER_GROUP_AXIS},0,0)/G001`,
  ]) {
    assert.equal(parseAddress(s), null, s);
  }
});

test("every group cell in a 3x3x3-cluster window decomposes to exactly one canonical address", () => {
  for (let cx = -1; cx <= 1; cx++)
    for (let cy = -1; cy <= 1; cy++)
      for (let cz = -1; cz <= 1; cz++) {
        const clusterCell = [BigInt(cx), BigInt(cy), BigInt(cz)];
        for (const [lx, ly, lz] of [[0, 0, 0], [19, 19, 19], [5, 10, 15], [1, 0, 19], [19, 0, 1]]) {
          const groupCell = [BigInt(lx), BigInt(ly), BigInt(lz)];
          assert.ok(isLocalGroupCell(groupCell));
          const global = addressToGlobalGroupCell(clusterCell, groupCell);
          const decomposed = globalGroupCellToAddress(global);
          assert.deepEqual(decomposed.clusterCell, clusterCell, `global=${global} decomposed to wrong clusterCell`);
          assert.deepEqual(decomposed.groupCell, groupCell, `global=${global} decomposed to wrong groupCell`);

          // Round-trip through the canonical string too.
          const addr = { clusterCell, groupCell, galaxyOrdinal: 0 };
          const s = formatAddress(addr);
          const reparsed = parseAddress(s);
          assert.deepEqual(reparsed.clusterCell, clusterCell, s);
          assert.deepEqual(reparsed.groupCell, groupCell, s);
        }
      }
});

test("galaxy world positions from two different address spellings of the same place are impossible (rejected)", () => {
  // The "same" global group cell 25 Mpc out on x can only be canonically
  // spelled as clusterCell=(1,0,0)/groupCell=(5,0,0) (25 = 1*20+5) - a
  // shifted-but-equivalent spelling like clusterCell=(0,0,0)/groupCell=
  // (25,0,0) refers to the same physical location under the old (buggy)
  // scheme but must now be REJECTED outright, not silently accepted with a
  // different galaxy set.
  const global = [25n, 0n, 0n];
  const canonical = globalGroupCellToAddress(global);
  assert.deepEqual(canonical, { clusterCell: [1n, 0n, 0n], groupCell: [5n, 0n, 0n] });

  const canonicalStr = formatAddress({ clusterCell: canonical.clusterCell, groupCell: canonical.groupCell, galaxyOrdinal: 0 });
  assert.ok(parseAddress(canonicalStr), "the canonical spelling must parse");

  const altStr = "U/K(0,0,0)/H(25,0,0)/G001";
  assert.equal(parseAddress(altStr), null, "the non-canonical alternate spelling must be rejected, not resolved");

  // Calling straight into resolveGalaxy/galaxiesInGroup with the rejected
  // spelling must also fail loudly (RangeError), never silently succeed
  // with a different galaxy set for "the same place".
  assert.throws(() => resolveGalaxy(SEED, { clusterCell: [0n, 0n, 0n], groupCell: [25n, 0n, 0n], galaxyOrdinal: 0 }), RangeError);
});

