// Regenerates tests/fixtures/fauna-continuity-562ff898.json from the running
// app: the canonical census record of the follow-up individual and its living
// species genome, plus its dated pose as observed by a grounded observer at
// each offset. tests/fauna-continuity.test.mjs replays these in Node.
// Usage: ATLAS_URL=http://127.0.0.1:5191/ ATLAS_HARDWARE=1 node tests/fauna-continuity-fixture.browser.mjs
import { chromium } from 'playwright';
import * as THREE from 'three';
import { writeFile } from 'node:fs/promises';
import { browserArgs } from './browser-options.mjs';
import { encodeVersions, CURRENT_VERSIONS } from '../src/time-nav.ts';

const base = process.env.ATLAS_URL || 'http://127.0.0.1:5191/';
const bodyId = 'G001/C2128,0,1/0/planet/1', seed = 'LETHRA-001';
const date = '435084631200000040194500000';
const targetId = `${bodyId}:fauna:562ff898`;
const offsets = [0, .25, .5, 1, 1.75, 3, 5, 10, 20, 30];
const local = new THREE.Vector3(4067765.96072781,-1507043.162624909,2860322.144626968);
const radius = 5194907.072465867;
const up = local.clone().normalize();
const tangent = new THREE.Vector3().crossVectors(Math.abs(up.y)>.92?new THREE.Vector3(1,0,0):new THREE.Vector3(0,1,0),up).normalize();
const eye = local.clone().addScaledVector(tangent,8).addScaledVector(up,1.64);
const at = s => (BigInt(date) + BigInt(Math.round(s * 1e9))).toString();
const browser = await chromium.launch({headless:true,args:browserArgs});
const observed = [];let census = null, species = null;
try {
  for (const s of offsets) {
    const t = at(s), page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
    await page.addInitScript(()=>{const def=Object.defineProperty;Object.defineProperty=function(o,k,d){const r=Reflect.apply(def,Object,[o,k,d]);if(o===window&&k==='__atlas'&&d?.value?.setExplorationPaused){d.value.setExplorationPaused(true);Object.defineProperty=def;}return r;};});
    const params = new URLSearchParams({seed,g:'G001',system:'G001/C2128,0,1/0',body:bodyId,walk:eye.toArray().join(','),date:t,wv:encodeVersions(CURRENT_VERSIONS)});
    await page.goto(`${base}?${params}`,{waitUntil:'networkidle'});
    await page.waitForFunction(({id,t})=>{const a=window.__atlas;return a?.ready&&a.state.body?.id===id&&a.date.offsetNs===t&&a.travel.walking?.grounded&&a.terrain?.tiles?.faunaDrawn?.length>0&&a.terrain.tiles.lifePending===0&&a.terrain.tiles.faunaTerrainPending===0;},{id:bodyId,t},{timeout:240000});
    const r = await page.evaluate(id=>{const a=window.__atlas,i=a.faunaTrace([id]).individuals[0];
      const sp=a.lifeGate?.faunaSpecies?.find(x=>x.id===i.census?.member?.speciesId)??null;
      return {i,species:sp?{id:sp.id,creature:sp.creature}:null,livingSpecies:a.lifeGate?.faunaSpecies?.length??0,walker:a.travel.walking.position,radiusM:a.state.body.radiusM};},targetId);
    if (!r.i.position) throw new Error(`target not resident at +${s}s: ${JSON.stringify(r.i)}`);
    census ??= r.i.census; species ??= r.species;
    if (JSON.stringify(census.member) !== JSON.stringify(r.i.census.member)) throw new Error('canonical member record changed between restores');
    observed.push({offsetS:s,worldNs:t,pose:r.i.pose,position:r.i.position,walker:r.walker,stage:r.i.stage});
    await page.close();
  }
} finally { await browser.close(); }
const fixture = {note:'Generated by tests/fauna-continuity-fixture.browser.mjs from exact-date restores of the saved walk address (grounded observer).',
  seed,bodyId,targetId,date,bodyRadiusM:radius,cellId:census.cellId,direction:census.direction,memberIndex:census.memberIndex,member:census.member,species,observed};
await writeFile('tests/fixtures/fauna-continuity-562ff898.json',JSON.stringify(fixture,null,1)+'\n');
console.log(JSON.stringify({cellId:fixture.cellId,memberIndex:fixture.memberIndex,species:species?.id,observed:observed.map(o=>[o.offsetS,o.pose.gait,o.pose.x,o.pose.z])},null,1));
